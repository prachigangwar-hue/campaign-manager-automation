# Function to generate lift
# What is Lift?
# Extra sale value generated by customers who have received communication.
# 
GENERATE_CAMP_LIFT <- function(data_basket,
                               varGroup = c("Campaign_Name","Test_Control"),
                               varBasket = "Average Customer Spend",
                               varSC = "Sale Customers",category_names = c("test" = "t","control" = "c")){
  # Selecting required columns
  data_basket  <- data_basket %>% select_at(.vars = c(varGroup,varBasket,varSC))

  # Converting Test and control into columns
  data_basket <- pivot_wider(data_basket,names_from = "Test_Control",values_from = c(varSC,varBasket))
  
  # Replacing na with 0
  data_basket[is.na(data_basket)] <- 0
  
  # Addding Diffenrence columns for basket size
  data_basket$Diff_Basket <-  data_basket[[paste0(varBasket,"_",category_names["test"])]] - data_basket[[paste0(varBasket,"_",category_names["control"])]]
  
  # Calculating Lift
  data_basket$Lift <- data_basket[[paste0(varSC,"_",category_names["test"])]] * data_basket$Diff_Basket
  
  return(data_basket)
}

# Function to generate shift
GENERATE_CAMP_SHIFT <- function(data_basket,
                                data_hitrate,
                               varGroup = c("Campaign_Name","Test_Control"),
                               varBasket = "Average Customer Spend",
                               varHR = "Hit Rate",
                               varDlrCust = "Delivery Customers",
                               category_names = c("test" = "t","control" = "c")){
  # Selecting required columns
  data_basket  <- data_basket  %>% select_at(.vars = c(varGroup,varBasket))
  data_hitrate <- data_hitrate %>% select_at(.vars = c(varGroup,varDlrCust,varHR))
  
  # Joining data
  data <- full_join(data_basket,data_hitrate)
  
  # Replacing NA with 0
  data[is.na(data)] <- 0
  
  # Converting Test and control into columns
  data <- pivot_wider(data,names_from = "Test_Control",values_from = c(varBasket,varHR,varDlrCust))
  
  # Replacing NA with 0
  data[is.na(data)] <- 0
  
  # Addding Diffenrence columns for hit rate
  data$Diff_HR <-  data[[paste0(varHR,"_",category_names["test"])]] - data[[paste0(varHR,"_",category_names["control"])]]
  
  # Calculating Shift
  data$Shift <- data[[paste0(varDlrCust,"_",category_names["test"])]] * data$Diff_HR * data[[paste0(varBasket,"_",category_names["test"])]]
  
  return(data)
}

