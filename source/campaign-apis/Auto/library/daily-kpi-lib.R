# Funciton to generate summary for repeat customers
GENERATE_SUMMARY_V1 <- function(data,values = list(),varId = "Customer Mobile",varFil = "M Last Transaction Date",nod = 730,subText = "2 years",retType = "info"){
  data <- data %>% filter_at(vars(varFil),~ . > as.Date((Sys.Date() - nod)))
  
  
  if(nrow(data) > 0){
    ret_list <- list()
    ret_list[["Repeat Customers"]]       <- nrow(data)
    ret_list[["Number of Bills_Repeat"]] <- sum(data$`Bill No_Total`)
    ret_list[["Net Amount SUM_Repeat"]]  <- sum(data$`Net Amount SUM_Total`)
    ret_list[["Bill Qty SUM_Repeat"]]    <- sum(data$`Bill Qty SUM_Total`)
    
    ret_list[["ACB_Repeat"]] <- ret_list[["Number of Bills_Repeat"]]/ret_list[["Repeat Customers"]]
    ret_list[["ACV_Repeat"]] <- ret_list[["Net Amount SUM_Repeat"]] /ret_list[["Repeat Customers"]]
    ret_list[["ACQ_Repeat"]] <- ret_list[["Bill Qty SUM_Repeat"]]   /ret_list[["Repeat Customers"]]
    
    ret_list[["Customer Out of Total"]]        <- round((ret_list[["Repeat Customers"]]      /values[["Number of Customers_Total"]]) * 100,2)
    ret_list[["Net Amount SUM Out of Total"]]  <- round((ret_list[["Net Amount SUM_Repeat"]] /values[["Net Amount SUM_Total"]])      * 100,2)
    ret_list[["Bill Qty SUM Out of Total"]]    <- round((ret_list[["Bill Qty SUM_Repeat"]]   /values[["Bill Qty SUM_Total"]])        * 100,2)
    ret_list[["Number of Bills Out of Total"]] <- round((ret_list[["Number of Bills_Repeat"]]/values[["Number of Bills_Total"]])     * 100,2)
    
    cat("Total repeat customers who have come in last", subText, "are", nrow(data), "which is", 
        ret_list[["Customer Out of Total"]], "% of total customers","\n")
    
    cat("Total bills generated by these custoemrs", "are", ret_list[["Number of Bills_Repeat"]],"which is",
        ret_list[["Number of Bills Out of Total"]],"% of total number of bills","\n")
    #  cat("Total quantity bought by these custoemrs", "is", ret_list[["Bill Qty SUM_Repeat"]],"which is",
    #      ret_list[["Bill Qty SUM Out of Total"]],"% of total Bill Quantities","\n")
    cat("Total value generated by these customers","is", ret_list[["Net Amount SUM_Repeat"]],"which is",
        ret_list[["Net Amount SUM Out of Total"]], "% of total sales","\n")
    
    # cat("ACB for repeat customers in ",subText,ret_list[["ACB_Repeat"]],"\n")
    # cat("ACV for repeat customers in ",subText,ret_list[["ACV_Repeat"]],"\n")
    # cat("ACQ for repeat customers in ",subText,ret_list[["ACQ_Repeat"]],"\n")
    if(retType != "info"){
      return(ret_list)
    }
  }else{
    print("data not found")
  }
}

