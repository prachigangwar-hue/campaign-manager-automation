# Now calculating metrics

# What is Delivery Rate?
# Number of communications got delivered on the customer mobile or whatsapp.
#
# What is Hit Rate?
#   Number of customers who hit the store after recieving the Communication.
#
# What is Lift?
#   Extra sale value generated by customers who have received communication.
# 
# What is Shift?
#   Extra sale value generated by extra customers who came as in result of communication.
# 
# What is ROAS(Return on Advertising spend)?
#   For every rupee we have spent, how many rupees have we earned.


# Function to generate rate
# If isRate = TRUE then Divided column will be multipled by 100
GENERATE_CAMP_AGG <- function(data_camp,
                          varGroup = c("Source Short Name"),
                          varNum = "Delivery Customers",
                          varDen = "Segment Customers",
                          colDiv = "Divided Column",
                          isRate = TRUE){
  # Selecting variables  
  data_camp <- data_camp %>% select_at(.vars = c(varGroup,varNum,varDen))
  
  head(data_camp)
  
  # Grouping variables
  data_camp <- data_camp %>% group_by_at(.vars = c(varGroup)) %>% summarise_at(vars(c(varNum,varDen)),sum)
  colnames(data_camp)[-c(1:length(varGroup))] <- c(varNum,varDen)
  
  # Generating Division column
  data_camp[[colDiv]] <- (data_camp[[varNum]]/data_camp[[varDen]])
  
  if(isRate == TRUE){
    data_camp[[colDiv]] <- round(100 * (data_camp[[colDiv]]),2)
  }  
  return(data_camp)
}


