  data_seg$Communication_Cost <- ifelse(data_seg$Test_Control == "test" & data_seg$Communication_Medium == "sms" & data_seg$Delivery_Status == "delivered", sms_cost,
                                      ifelse(data_seg$Test_Control == "test" & data_seg$Communication_Medium == "whatsapp" & data_seg$Delivery_Status == "delivered",wa_cost,0))
  
