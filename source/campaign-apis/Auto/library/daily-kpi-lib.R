# Function to generate ROAS
GENERATE_CAMP_ROAS <- function(data_lift,
                               data_shift,
                               data_commcost,
                               varGroup = c("Campaign_Name")){
  
  # Joining Data
  data <- full_join(data_lift,data_shift,by  = varGroup) %>% full_join(data_commcost,by  = varGroup)
  
  # Replacing Na with 0
  data[is.na(data)] <- 0
  
  # Calculating ROAS
  data[["Total Benifit"]] <- data[["Lift"]]  + data[["Shift"]]
  data[["ROAS"]] <- data[["Total Benifit"]] / data[["Communication_Cost_test"]]
  
  # Replacing Na with 0
  data[is.na(data)] <- 0
  
  
  return(data)
}


