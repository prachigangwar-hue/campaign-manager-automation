#' Function to generate delivery kpis
#' 
#' Input:
#' 
#' It takes two arguments:
#' 
#' data_repeat: repeat customer data, as delivery reports are for the existing customers only
#' data_dlr: delivery reports for a communication campaign
#' 
#' Output:
#' text with customers sale details from deliverd communications & other delivery kpis'



GENERATE_DELIVERY_KPIS <- function(data_repeat,data_dlr){
  
  # Delivery KPI's
  dt_dlr_kpi <- list(
                "Total_Customers" = n_distinct(data_dlr[["Customer Mobile"]]),
                "Delivered_Customers" = n_distinct(data_dlr[["Customer Mobile"]][data_dlr[["Delivery_Status"]] == "delivered"]),
                "Not_Delivered_Customers" = n_distinct(data_dlr[["Customer Mobile"]][data_dlr[["Delivery_Status"]] == "not_delivered"])
                )
  
  # Filtering and joining 
  data_dlr <- data_dlr %>% filter(Delivery_Status == "delivered")
  data_repeat <- inner_join(data_repeat,data_dlr %>% select(`Customer Mobile`),by = "Customer Mobile")
  
  dt_repeat_kpi <- list(
    "Customers_Total"           = n_distinct(data_repeat$`Customer Mobile`),
    "Net Amount SUM_Total"      = sum(data_repeat$`Net Amount SUM_Total`),
    "Bill Qty SUM_Total"        = sum(data_repeat$`Bill Qty SUM_Total`),
    "Number of Bills_Total"     = sum(data_repeat$`Bill No_Total`))
  
  
  text_dlr <- paste0(
                    "We have sent ",
                    dt_dlr_kpi[["Total_Customers"]]," ",
                    
                    "communications yesterday, we have got"," ",
                    
                    round(100*(dt_dlr_kpi[["Delivered_Customers"]]/dt_dlr_kpi[["Total_Customers"]]),2),
                    
                    "% of delivery rate."," ","Out of these ",
                    
                    dt_repeat_kpi[["Customers_Total"]]," ",
                    "customers (Hit Rate is ",
                    
                    round(100*(dt_repeat_kpi[["Customers_Total"]]/dt_dlr_kpi[["Delivered_Customers"]]),0),
                    
                    "%)",
                    " have generated sale value of Rs.",
                    
                    round(dt_repeat_kpi[["Net Amount SUM_Total"]]/100000,0),"L.",
                    
                    " with ABV of Rs.",
                    
                    round(dt_repeat_kpi[["Net Amount SUM_Total"]]/dt_repeat_kpi[["Number of Bills_Total"]])

  )
  
  ret_list <- list("text_dlr" = text_dlr)  
  return(ret_list)
  
}


