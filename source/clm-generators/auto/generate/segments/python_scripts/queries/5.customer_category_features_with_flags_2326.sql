CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Boys_Senior' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Boys_Senior_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Toddler' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Toddler_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'FMCG_Food' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS FMCG_Food_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Infant' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Infant_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'FMCG_Non_Food' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS FMCG_Non_Food_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Women' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Women_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Men' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Men_FLAG,
