SUM(CASE WHEN COMBINED_CATEGORY = 'Infant' THEN QTY ELSE 0 END) / NULLIF(SUM(QTY),0) AS Infant_PCT_QTY,
SUM(CASE WHEN COMBINED_CATEGORY = 'FMCG_Non_Food' THEN QTY ELSE 0 END) / NULLIF(SUM(QTY),0) AS FMCG_Non_Food_PCT_QTY,
SUM(CASE WHEN COMBINED_CATEGORY = 'Women' THEN QTY ELSE 0 END) / NULLIF(SUM(QTY),0) AS Women_PCT_QTY,
SUM(CASE WHEN COMBINED_CATEGORY = 'Men' THEN QTY ELSE 0 END) / NULLIF(SUM(QTY),0) AS Men_PCT_QTY,
SUM(CASE WHEN COMBINED_CATEGORY = 'Girls_Junior' THEN QTY ELSE 0 END) / NULLIF(SUM(QTY),0) AS Girls_Junior_PCT_QTY,
SUM(CASE WHEN COMBINED_CATEGORY = 'Girls_Senior' THEN QTY ELSE 0 END) / NULLIF(SUM(QTY),0) AS Girls_Senior_PCT_QTY,
