CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Home_Mart' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Home_Mart_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Boys' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Boys_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Girls' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Girls_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Staples' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Staples_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Toys' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Toys_FLAG,
CASE WHEN SUM(CASE WHEN COMBINED_CATEGORY = 'Women_Ethnic' THEN QTY ELSE 0 END) > 0 THEN 1 ELSE 0 END AS Women_Ethnic_FLAG,
