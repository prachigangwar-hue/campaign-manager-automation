SUM(CASE WHEN COMBINED_CATEGORY = 'Toys' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Toys_PCT_REVENUE,
SUM(CASE WHEN COMBINED_CATEGORY = 'Women_Ethnic' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Women_Ethnic_PCT_REVENUE,
SUM(CASE WHEN COMBINED_CATEGORY = 'Women_Western' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Women_Western_PCT_REVENUE,
-- 2) % Qty Contribution columns
SUM(CASE WHEN COMBINED_CATEGORY = 'Boys_Junior' THEN QTY ELSE 0 END) / NULLIF(SUM(QTY),0) AS Boys_Junior_PCT_QTY,
SUM(CASE WHEN COMBINED_CATEGORY = 'Boys_Senior' THEN QTY ELSE 0 END) / NULLIF(SUM(QTY),0) AS Boys_Senior_PCT_QTY,
