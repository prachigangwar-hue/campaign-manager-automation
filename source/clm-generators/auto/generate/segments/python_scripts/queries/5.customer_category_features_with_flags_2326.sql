SUM(CASE WHEN COMBINED_CATEGORY = 'Girls_Junior' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Girls_Junior_PCT_REVENUE,
SUM(CASE WHEN COMBINED_CATEGORY = 'Girls_Senior' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Girls_Senior_PCT_REVENUE,
SUM(CASE WHEN COMBINED_CATEGORY = 'Others' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Others_PCT_REVENUE,
SUM(CASE WHEN COMBINED_CATEGORY = 'Home_Mart' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Home_Mart_PCT_REVENUE,
SUM(CASE WHEN COMBINED_CATEGORY = 'Boys' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Boys_PCT_REVENUE,
SUM(CASE WHEN COMBINED_CATEGORY = 'Girls' THEN NETAMT ELSE 0 END) / NULLIF(SUM(NETAMT),0) AS Girls_PCT_REVENUE,
